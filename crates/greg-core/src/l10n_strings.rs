#[cfg(test)]
pub(super) static ALL_TABLES: &[(&str, &[(&str, &str)])] = &[
    ("en", STRINGS_EN),
    ("de", STRINGS_DE),
    ("fr", STRINGS_FR),
    ("es", STRINGS_ES),
    ("it", STRINGS_IT),
    ("ja", STRINGS_JA),
    ("pl", STRINGS_PL),
    ("ru", STRINGS_RU),
    ("zh", STRINGS_ZH),
];

fn lookup(table: &'static [(&'static str, &'static str)], key: &str) -> Option<&'static str> {
    table
        .binary_search_by(|probe| probe.0.cmp(key))
        .ok()
        .map(|i| table[i].1)
}

/// Raw localized string for `key` in `lang` (`de`, `fr`, `es`, `it`, `ja`, `pl`, `ru`, `zh`, `en`).
/// Transparently falls back to `STRINGS_EN` when a key is not present in the language table,
/// and returns `None` only when the key is unknown in English as well.
pub fn get_raw(lang: &str, key: &str) -> Option<&'static str> {
    let code = super::resolve_lang_code(lang);
    let table = match code {
        "de" => STRINGS_DE,
        "fr" => STRINGS_FR,
        "es" => STRINGS_ES,
        "it" => STRINGS_IT,
        "ja" => STRINGS_JA,
        "pl" => STRINGS_PL,
        "ru" => STRINGS_RU,
        "zh" => STRINGS_ZH,
        _ => STRINGS_EN,
    };
    lookup(table, key).or_else(|| lookup(STRINGS_EN, key))
}

/// Number of localized keys in the primary English table.
pub fn key_count() -> usize {
    STRINGS_EN.len()
}
